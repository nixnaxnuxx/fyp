-- FYP Supervision Portal - Supabase schema
-- Run this in Supabase SQL Editor once.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'student' check (role in ('supervisor','student')),
  created_at timestamptz not null default now()
);

create table if not exists public.academic_years (
  id uuid primary key default gen_random_uuid(),
  label text not null unique,
  start_year int not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.students (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid references public.profiles(id) on delete set null,
  academic_year_id uuid not null references public.academic_years(id) on delete restrict,
  full_name text not null,
  email text not null,
  student_no text,
  created_at timestamptz not null default now(),
  unique(email, academic_year_id)
);

create table if not exists public.projects (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null unique references public.students(id) on delete cascade,
  title text not null,
  description text,
  semester int not null default 1 check (semester in (1,2)),
  created_at timestamptz not null default now()
);

create table if not exists public.tasks (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  instructions text,
  evidence_requirements text,
  stage text,
  semester int not null default 1 check (semester in (1,2)),
  open_at timestamptz,
  due_at timestamptz not null,
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.task_assignments (
  id uuid primary key default gen_random_uuid(),
  task_id uuid not null references public.tasks(id) on delete cascade,
  student_id uuid not null references public.students(id) on delete cascade,
  assigned_at timestamptz not null default now(),
  unique(task_id,student_id)
);

create table if not exists public.submissions (
  id uuid primary key default gen_random_uuid(),
  task_id uuid not null references public.tasks(id) on delete cascade,
  student_id uuid not null references public.students(id) on delete cascade,
  summary text,
  results text,
  interpretation text,
  problems text,
  next_action text,
  report_section text,
  external_link text,
  status text not null default 'submitted' check (status in ('submitted','resubmitted','approved','revision_required','incomplete')),
  revision_no int not null default 1,
  submitted_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(task_id,student_id)
);

create table if not exists public.submission_files (
  id uuid primary key default gen_random_uuid(),
  submission_id uuid not null references public.submissions(id) on delete cascade,
  student_id uuid not null references public.students(id) on delete cascade,
  storage_path text not null,
  file_name text not null,
  file_type text,
  file_size bigint,
  uploaded_at timestamptz not null default now()
);

create table if not exists public.feedback (
  id uuid primary key default gen_random_uuid(),
  submission_id uuid not null references public.submissions(id) on delete cascade,
  supervisor_id uuid references public.profiles(id),
  decision text not null check (decision in ('approved','revision_required','incomplete')),
  comment text,
  revision_due_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.audit_events (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id),
  entity_type text not null,
  entity_id uuid,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

-- Create/refresh profile automatically when a user signs up.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,full_name,role)
  values(new.id,coalesce(new.raw_user_meta_data->>'full_name',new.email),'student')
  on conflict(id) do nothing;

  update public.students
  set profile_id=new.id
  where lower(email)=lower(new.email) and profile_id is null;
  return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_supervisor()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='supervisor');
$$;

create or replace function public.current_student_id()
returns uuid language sql stable security definer set search_path=public as $$
  select s.id from public.students s
  where s.profile_id=auth.uid() or lower(s.email)=lower(coalesce(auth.jwt()->>'email',''))
  order by s.created_at desc limit 1;
$$;

