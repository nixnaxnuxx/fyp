create policy "profiles own or supervisor read" on public.profiles for select using (id=auth.uid() or public.is_supervisor());
create policy "profiles own update" on public.profiles for update using (id=auth.uid()) with check (id=auth.uid());

create policy "academic years authenticated read" on public.academic_years for select to authenticated using (true);
create policy "academic years supervisor write" on public.academic_years for all to authenticated using (public.is_supervisor()) with check (public.is_supervisor());

create policy "students own or supervisor read" on public.students for select to authenticated using (public.is_supervisor() or id=public.current_student_id());
create policy "students supervisor write" on public.students for all to authenticated using (public.is_supervisor()) with check (public.is_supervisor());

create policy "projects own or supervisor read" on public.projects for select to authenticated using (public.is_supervisor() or student_id=public.current_student_id());
create policy "projects supervisor write" on public.projects for all to authenticated using (public.is_supervisor()) with check (public.is_supervisor());

create policy "tasks assigned or supervisor read" on public.tasks for select to authenticated using (
  public.is_supervisor() or exists(select 1 from public.task_assignments a where a.task_id=tasks.id and a.student_id=public.current_student_id())
);
create policy "tasks supervisor write" on public.tasks for all to authenticated using (public.is_supervisor()) with check (public.is_supervisor());

create policy "assignments own or supervisor read" on public.task_assignments for select to authenticated using (public.is_supervisor() or student_id=public.current_student_id());
create policy "assignments supervisor write" on public.task_assignments for all to authenticated using (public.is_supervisor()) with check (public.is_supervisor());

create policy "submissions own or supervisor read" on public.submissions for select to authenticated using (public.is_supervisor() or student_id=public.current_student_id());
create policy "students insert own submissions" on public.submissions for insert to authenticated with check (student_id=public.current_student_id());
create policy "students update own submissions" on public.submissions for update to authenticated using (student_id=public.current_student_id() or public.is_supervisor()) with check (student_id=public.current_student_id() or public.is_supervisor());

create policy "submission files own or supervisor read" on public.submission_files for select to authenticated using (public.is_supervisor() or student_id=public.current_student_id());
create policy "submission files student insert" on public.submission_files for insert to authenticated with check (student_id=public.current_student_id());

create policy "feedback own or supervisor read" on public.feedback for select to authenticated using (public.is_supervisor() or exists(select 1 from public.submissions s where s.id=feedback.submission_id and s.student_id=public.current_student_id()));
create policy "feedback supervisor write" on public.feedback for all to authenticated using (public.is_supervisor()) with check (public.is_supervisor());

create policy "audit supervisor read" on public.audit_events for select to authenticated using (public.is_supervisor());
create policy "audit authenticated insert" on public.audit_events for insert to authenticated with check (actor_id=auth.uid());

-- Storage bucket. Private by default; files are opened through signed URLs.
insert into storage.buckets(id,name,public,file_size_limit)
values('fyp-evidence','fyp-evidence',false,52428800)
on conflict(id) do update set public=false,file_size_limit=52428800;

create policy "evidence upload own folder" on storage.objects for insert to authenticated with check (
  bucket_id='fyp-evidence' and (public.is_supervisor() or split_part(name,'/',1)=public.current_student_id()::text)
);
create policy "evidence read own folder or supervisor" on storage.objects for select to authenticated using (
  bucket_id='fyp-evidence' and (public.is_supervisor() or split_part(name,'/',1)=public.current_student_id()::text)
);
create policy "evidence delete own folder or supervisor" on storage.objects for delete to authenticated using (
  bucket_id='fyp-evidence' and (public.is_supervisor() or split_part(name,'/',1)=public.current_student_id()::text)
);

